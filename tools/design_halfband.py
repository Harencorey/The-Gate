# Designs the Micro Glow oversampling halfband filters and writes Source/HalfbandCoeffs.h.
#   python3 tools/design_halfband.py
import numpy as np
from scipy import signal

def halfband(N, fp):
    """Equiripple halfband, N = 4k-1 taps, passband edge fp (cycles/sample at the higher rate)."""
    assert N % 4 == 3
    # Vaidyanathan trick: design a (N+1)/2-tap one-band filter g, then interleave with zeros.
    M = (N + 1) // 2
    g = signal.remez(M, [0, 2 * fp, 0.5, 0.5], [1, 0], fs=1.0)   # single band 0..2fp, tiny stop at 0.5
    h = np.zeros(N)
    h[0::2] = g / 2
    h[(N - 1) // 2] = 0.5
    return h

def report(h, fp, name):
    w, H = signal.freqz(h, worN=1 << 16, fs=1.0)
    mag = 20 * np.log10(np.abs(H) + 1e-20)
    pb = mag[w <= fp]
    sb = mag[w >= 0.5 - fp]
    print(f"{name}: {len(h)} taps, pass ripple {pb.max()-pb.min():.5f} dB, stop {sb.max():.1f} dB, latency {(len(h)-1)//2} samples")
    return mag, w

# Stage A: base <-> 2x. Pass to 0.221 x (2x rate) = 19.5 kHz at 44.1k, 21.2 kHz at 48k.
fpA = 0.221
best = None
for N in range(39, 140, 4):
    h = halfband(N, fpA)
    w, H = signal.freqz(h, worN=1 << 15, fs=1.0)
    stop = 20 * np.log10(np.abs(H[w >= 0.5 - fpA]).max())
    if stop < -80:
        best = h; break
hA = best
report(hA, fpA, "Stage A")

# Stage B: 2x <-> 4x. Content is below 0.1105 (4x rate); images start at 0.3895.
fpB = 0.1105
for N in range(7, 60, 4):
    h = halfband(N, fpB)
    w, H = signal.freqz(h, worN=1 << 15, fs=1.0)
    if 20 * np.log10(np.abs(H[w >= 0.5 - fpB]).max()) < -90:
        hB = h; break
report(hB, fpB, "Stage B")

# Pad stage B to 4k+1 taps (zero at both ends) so its round trip is a whole number of base samples
hB = np.concatenate([[0.0], hB, [0.0]])

# Stage C: 4x <-> 8x. Content is below 0.0553 (8x rate); images start at 0.4447.
fpC = 0.05525
for N in range(3, 40, 4):
    h = halfband(N, fpC)
    w, H = signal.freqz(h, worN=1 << 15, fs=1.0)
    if 20 * np.log10(np.abs(H[w >= 0.5 - fpC]).max()) < -100:
        hC = h; break
report(hC, fpC, "Stage C")
# pad so the round trip ((len-1)/8 base samples) is whole
while (len(hC) - 1) % 8:
    hC = np.concatenate([[0.0], hC, [0.0]])

# round trip at 44.1k: up A, up B, down B, down A (each filter applied once up and once down)
for fs in (44100, 48000):
    f = np.array([20, 100, 1000, 10000, 15000, 18000, 19000, 20000, 21000])
    _, HA = signal.freqz(hA, worN=f, fs=2 * fs)
    _, HB = signal.freqz(hB, worN=f, fs=4 * fs)
    _, HC = signal.freqz(hC, worN=f, fs=8 * fs)
    rt = 20 * np.log10(np.abs(HA * HB * HC) ** 2)
    print(f"round trip at {fs}: " + ", ".join(f"{int(x)} Hz {v:+.3f}" for x, v in zip(f, rt)))

latA = (len(hA) - 1) // 2
latB = (len(hB) - 1) // 2
latC = (len(hC) - 1) // 2
assert latB % 2 == 0 and latC % 4 == 0
print(f"Latency: 8x = {latA + latB // 2 + latC // 4}, 4x = {latA + latB // 2}, 2x = {latA} base samples")

def arr(name, h):
    body = ",\n    ".join(", ".join(f"{v:.17g}" for v in h[i:i + 4]) for i in range(0, len(h), 4))
    return f"inline constexpr double {name}[{len(h)}] = {{\n    {body}\n}};\n"

with open("Source/HalfbandCoeffs.h", "w") as f:
    f.write("#pragma once\n// GENERATED by tools/design_halfband.py - do not edit by hand.\n"
            "// Linear-phase equiripple halfband filters for Micro Glow's oversampling.\n"
            f"// Stage A (base <-> 2x): {len(hA)} taps, passes 0..{fpA} of the 2x rate, >= 80 dB stopband.\n"
            f"// Stage B (2x <-> 4x): {len(hB)} taps (end taps zero), >= 90 dB stopband.\n"
            f"// Stage C (4x <-> 8x): {len(hC)} taps (end taps zero), >= 100 dB stopband.\n\n"
            "namespace tg::hb\n{\n")
    f.write(arr("stageA", hA))
    f.write(arr("stageB", hB))
    f.write(arr("stageC", hC))
    f.write("}\n")
print("wrote Source/HalfbandCoeffs.h")
